const DICTS: Record<Lang, Partial<Record<Key, string>>> = { es, ja, en }

export type TFunc = (key: Key, vars?: Record<string, string | number>) => string

export function translator(lang: Lang): TFunc {
  const dict = DICTS[lang] ?? es
  return (key, vars) => {
    let s = dict[key] ?? es[key] ?? String(key)
    if (vars) {
      for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v))
    }
    return s
  }
}

